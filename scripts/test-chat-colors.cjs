const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const logic = {};
vm.createContext(logic);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../quickshell/app/ChatColors.js'), 'utf8'), logic);
const ids = ['participant_a', 'participant_b', 'room', 'friends', 'test_room', 'games', 'participant_c', 'work'];
const encoded = logic.assign('{}', ids);
const colors = JSON.parse(encoded);
assert.equal(new Set(Object.values(colors)).size, ids.length);
assert.equal(logic.assign('{}', [...ids].reverse()), encoded);
assert.equal(logic.assign(encoded, ['new-chat', ...ids]), logic.assign(encoded, [...ids, 'new-chat']));
const extended = JSON.parse(logic.assign(encoded, ['new-chat', ...ids]));
ids.forEach(id => assert.equal(extended[id], colors[id]));
assert.equal(logic.assign(encoded, ['participant_b']), encoded, 'closed/deleted chats retain their assignment');
assert.equal(logic.assign(encoded, [...ids, 'participant_b']), encoded);
const many = JSON.parse(logic.assign('{}', Array.from({length: 300}, (_, i) => `chat-${i}`)));
assert.equal(new Set(Object.values(many)).size, 300, 'larger histories do not repeat exact colors');
Object.values(many).forEach(color => assert.match(color, /^#[a-f0-9]{6}$/));
assert.deepEqual(JSON.parse(logic.assign('invalid-json', ['a'])), {a: logic.swatches[0]});
assert.equal(Object.keys(logic.parse('{"a":"not-a-color","b":3}')).length, 0);
assert.equal(JSON.parse(logic.assign('{}', ['__proto__', 'constructor'])).__proto__, logic.swatches[0]);
console.log('Chat colors: distinct assignments, stable identity, history growth, and malformed state passed');
