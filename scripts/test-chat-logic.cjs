const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const logic = {};
vm.createContext(logic);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../quickshell/app/ChatLogic.js'), 'utf8'), logic);
const tabs = value => Array.from(value);
assert.deepEqual(tabs(logic.reconcileTabs(['a', 'b'], [{id:'b'}, {id:'a'}, {id:'c'}])), ['a','b','c']);
assert.deepEqual(tabs(logic.reconcileTabs(['a','b'], [{id:'a',tab_closed:true}, {id:'b'}])), ['b']);
assert.deepEqual(tabs(logic.reconcileTabs(['b'], [{id:'a',tab_closed:false}, {id:'b'}])), ['b','a']);
const old = {self:{id:'me'}, messages:[{id:'1',sender:{id:'friend'}}]};
const incoming = {self:{id:'me'}, messages:[...old.messages,{id:'2',sender:{id:'friend'}}]};
const own = {self:{id:'me'}, messages:[...old.messages,{id:'3',sender:{id:'me'}}]};
assert.equal(logic.hasIncomingMessage(null, incoming, 'message_created'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'server_reconnected'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'message_updated'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'message_deleted'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'message_created'), true);
assert.equal(logic.hasIncomingMessage(incoming, incoming, 'message_created'), false);
assert.equal(logic.hasIncomingMessage(old, own, 'message_created'), false);
assert.equal(logic.shouldPlaySound(true, false, false, 50), true);
assert.equal(logic.shouldPlaySound(true, true, false, 50), false);
assert.equal(logic.shouldPlaySound(true, false, true, 50), false);
assert.equal(logic.shouldPlaySound(true, false, false, 0), false);
console.log('Chat tab ordering and notification focus/mute/volume tests passed');
