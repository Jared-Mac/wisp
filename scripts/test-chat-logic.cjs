const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const logic = {};
vm.createContext(logic);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../quickshell/app/ChatLogic.js'), 'utf8'), logic);
const tabs = value => Array.from(value);
assert.deepEqual(tabs(logic.reconcileTabs(['a', 'b'], [{id:'b'}, {id:'a'}, {id:'c'}])), ['a','b','c']);
assert.deepEqual(tabs(logic.reconcileTabs(['a','b'], [{id:'a',tab_closed:true}, {id:'b'}])), ['b']);
assert.deepEqual(tabs(logic.reconcileTabs(['b'], [{id:'a',tab_closed:false}, {id:'b'}])), ['b','a']);
const old = {self:{id:'me'}, messages:[{id:'1',sender:{id:'friend'}}]};
const incoming = {self:{id:'me'}, messages:[...old.messages,{id:'2',sender:{id:'friend'}}]};
const own = {self:{id:'me'}, messages:[...old.messages,{id:'3',sender:{id:'me'}}]};
assert.equal(logic.hasIncomingMessage(null, incoming, 'message_created'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'server_reconnected'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'message_updated'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'message_deleted'), false);
assert.equal(logic.hasIncomingMessage(old, incoming, 'message_created'), true);
assert.equal(logic.hasIncomingMessage(incoming, incoming, 'message_created'), false);
assert.equal(logic.hasIncomingMessage(old, own, 'message_created'), false);
assert.equal(logic.shouldPlaySound(true, false, false, 50), true);
assert.equal(logic.shouldPlaySound(true, true, false, 50), false);
assert.equal(logic.shouldPlaySound(true, false, true, 50), false);
assert.equal(logic.shouldPlaySound(true, false, false, 0), false);
console.log('Chat tab ordering and notification focus/mute/volume tests passed');
const twoChats = {self:{id:'me'}, messages:[{id:'4',conversation_id:'test_room',sender:{id:'friend'}},{id:'5',conversation_id:'dm',sender:{id:'friend'}}]};
assert.deepEqual(tabs(logic.incomingConversationIds(old,twoChats,'message_created')), ['test_room','dm']);
assert.deepEqual(tabs(logic.incomingConversationIds(old,twoChats,'server_reconnected')), []);
assert.deepEqual(tabs(logic.incomingConversationIds(twoChats,twoChats,'message_created')), []);
assert.equal(logic.shouldNotifyChat('dm','test_room',true,'other_chats',[],false,50),true);
assert.equal(logic.shouldNotifyChat('test_room','test_room',true,'other_chats',[],false,50),false);
assert.equal(logic.shouldNotifyChat('dm','test_room',true,'unfocused',[],false,50),false);
assert.equal(logic.shouldNotifyChat('dm','',false,'unfocused',[],false,50),true);
assert.equal(logic.shouldNotifyChat('test_room','test_room',true,'always',[],false,50),true);
assert.equal(logic.shouldNotifyChat('dm','test_room',true,'other_chats',['dm'],false,50),false);
assert.equal(logic.shouldNotifyChat('dm','',false,'always',['dm'],false,50),false);
assert.equal(logic.shouldNotifyChat('dm','',false,'always',[],true,50),false);
assert.equal(logic.shouldNotifyChat('dm','',false,'always',[],false,0),false);
console.log('Per-chat notification policies, focus, muted chats and reconnect suppression passed');
const room = members => ({self:{id:'me',hangout_id:'test_room'},hangouts:[{id:'test_room',members:members.map(id=>({id}))}]});
const outside={self:{id:'me',hangout_id:null},hangouts:[]};
assert.deepEqual(tabs(logic.roomSoundEvents(outside,room(['me']),'hangout_changed')),['self_join']);
assert.deepEqual(tabs(logic.roomSoundEvents(room(['me']),outside,'hangout_changed')),['self_leave']);
assert.deepEqual(tabs(logic.roomSoundEvents(room(['me']),room(['me','friend']),'server_state_changed')),['member_join']);
assert.deepEqual(tabs(logic.roomSoundEvents(room(['me','friend']),room(['me']),'server_state_changed')),['member_leave']);
assert.deepEqual(tabs(logic.roomSoundEvents(null,room(['me','friend']),'snapshot')),[]);
assert.deepEqual(tabs(logic.roomSoundEvents(room(['me']),room(['me','friend']),'server_reconnected')),[]);
assert.deepEqual(tabs(logic.roomSoundEvents(room(['me','friend']),room(['friend','me']),'server_state_changed')),[]);
assert.deepEqual(tabs(logic.roomSoundEvents(outside,{...outside,hangouts:[{id:'other',members:[{id:'friend'}]}]},'server_state_changed')),[]);
console.log('Four room sounds are distinct and restricted to actual membership transitions');
